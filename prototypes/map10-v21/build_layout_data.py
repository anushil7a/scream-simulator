"""Create and validate the static data module consumed by the standalone place."""
import argparse
import json
from math import atan2, degrees, hypot
from pathlib import Path

DIR=Path(__file__).resolve().parent
data=json.loads((DIR/"layout.json").read_text())
links=json.loads((DIR/"overworld_links.json").read_text())
assert set(links)=={"-".join(pair) for pair in data["plannedZone09Links"]}
for name,path in links.items():
    for key,p in zip(name.split("-"),(path[0],path[-1])):
        d=data["districts"][key];x,y,z=d["center"];w,h=d["size"];a,b,c=p
        assert b==y and (abs(a-x)==w/2 and abs(c-z)<=h/2-20 or abs(c-z)==h/2 and abs(a-x)<=w/2-20), (name,key,p)
    for i,(a,b) in enumerate(zip(path,path[1:])):
        dx,dz=[abs(b[j]-a[j]) for j in (0,2)]
        flat=hypot(dx,dz)-16*sum((i>0,i+2<len(path)))
        assert bool(dx) != bool(dz) and flat>0 and degrees(atan2(abs(b[1]-a[1]),flat))<=32, (name,a,b,flat)
data["worldLinks"]=links
def encode(v):
    if isinstance(v,dict):return "{"+",".join(f"[{json.dumps(k)}]={encode(s)}" for k,s in v.items())+"}"
    if isinstance(v,list):return "{"+",".join(map(encode,v))+"}"
    return json.dumps(v,ensure_ascii=False)
content="-- Generated by build_layout_data.py; edit JSON sources instead.\nreturn "+encode(data)+"\n"
p=DIR/"OverworldLayout.luau"
if argparse.ArgumentParser().parse_known_args()[1]==["--check"]:
    assert p.read_text()==content, "OverworldLayout.luau is stale."
else:
    p.write_text(content)
print("MAP-10 v2.1 data: nine districts, 11 bridged links and slope budget checked.")
